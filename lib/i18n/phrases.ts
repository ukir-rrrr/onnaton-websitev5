/** Translate a Japanese source string; fall back to the original. */
export function tr(locale: Locale, ja: string): string {
  if (locale === "yue" && yuePhrases[ja]) return yuePhrases[ja];
  if (locale === "zhTw" && zhTwPhrases[ja]) return zhTwPhrases[ja];
  const hit = phrases[ja] ?? phrases[ja.replace(/\n/g, "")];
  if (!hit) return ja;
  return t(locale, hit);
}

/** Translate a string that may include a full-width space compound. */
export function trName(locale: Locale, ja: string): string {
  if (phrases[ja]) return tr(locale, ja);
  const parts = ja.split("　");
  if (parts.length > 1) {
    return parts.map((part) => tr(locale, part)).join(locale === "ja" ? "　" : " ");
  }
  return ja;
}
